import 'dart:math' as math;

import 'package:hgf_fit/hgf_fit.dart';
import 'package:hgf_fit/ir.dart' show irResponseOf;

import '../ir.dart';
import '../trial.dart';

/// Marks an absent per-subject array in the subject table.
const int noData = 0xffffffff;

/// Entries per subject in the subject table: trial count, then the offsets
/// (in 32-bit words of the data buffer) of its inputs, observed mask, time
/// steps and responses ([noData] where absent).
const int subjectStride = 5;

/// An [HgfModel]'s likelihood compiled into a WGSL compute shader: one
/// invocation per batch element (a subject and a parameter vector), with
/// the parameters set from the pass inside the kernel and, with
/// [directions] > 0, the derivative of the likelihood along each parameter
/// (forward-mode tangents through the unrolled trial).
///
/// Bindings (group 0): 0 `state` (read_write `f32`, `[slot][element]`),
/// 1 `data` (the subjects' series, `u32` words), 2 `params` (uniform: batch
/// size, first trial, trial count), 3 `job` (`u32`: each element's
/// subject, the initial slots, then the constrained parameters `[i][e]` and
/// `dx/dy` `[i][e]` as `f32` bits), 4 `subj` (the subject table), and with
/// tangents 5 `tang` (read_write `f32`, `[slot][direction][element]`).
///
/// After the last dispatch, slot [resultSlot] holds each element's negative
/// log-likelihood (`3.4e38` where it stopped being finite), and the
/// [directions] slots after it its gradient with respect to the
/// unconstrained parameters.
///
/// With [reverse], the gradient comes from reverse mode instead (adjoints,
/// see `docs/DIFFERENTIATION.md` §7): [source] is then the primal, which
/// also stores the carried state every [checkpoint] trials in `tape`
/// (binding 5, `[checkpoint][slot][element]`), and [reverseSource] walks
/// the segments back, last first: it recomputes each segment from its
/// checkpoint into `seg` (binding 6) and runs the trial's adjoint
/// statements backwards, keeping the carried slots' adjoints in `adj`
/// (binding 7) between dispatches. Its uniform is `B`, the segment to
/// start below, the number of segments, and the total segment count; the
/// dispatch that reaches segment 0 writes the gradient where the tangent
/// kernel would. The cost is a fixed multiple of the primal (~3–10×)
/// whatever the number of parameters, where forward mode grows with it.
final class FitKernel {
  /// Compiles [model]'s likelihood; with [gradients], also its gradient
  /// (needs `HgfModel.hasExactGradients`), by forward-mode tangents or
  /// with [reverse] by reverse mode, checkpointing every [checkpoint]
  /// trials (for series of up to `checkpoint²` trials, one checkpoint
  /// every √T trials is the cheapest).
  ///
  /// Throws [UnsupportedError] for networks, parameters or response models
  /// without a GPU kernel.
  factory FitKernel(
    HgfModel model, {
    bool gradients = false,
    bool reverse = false,
    int checkpoint = 32,
    int workgroupSize = 64,
  }) {
    if (gradients && !model.hasExactGradients) {
      throw UnsupportedError('The model has no exact gradients');
    }
    if (reverse && !gradients) {
      throw ArgumentError('reverse needs gradients');
    }
    if (reverse && checkpoint < 1) {
      throw ArgumentError.value(checkpoint, 'checkpoint', 'Must be ≥ 1');
    }
    final response = gpuResponseOf(model.response);
    final k = gradients ? model.dimension : 0;
    // Tangent directions in the kernel (none in reverse mode, whose job
    // layout still carries dx/dy for the k parameters).
    final kt = reverse ? 0 : k;
    final c = TrialCompiler(model.network, response, directions: kt);
    // The slot variable each parameter sets (the last one wins, as on the
    // CPU).
    final paramOf = <String, int>{};
    final responseNames = model.response.parameters.keys.toList();
    for (var i = 0; i < model.dimension; i++) {
      for (final t in model.parameters[i].targets) {
        final v = switch (t) {
          NodeTarget(:final node, :final field) =>
            gpuNodeFields.contains(field)
                ? TrialCompiler.fieldVar(node, field)
                : throw UnsupportedError('No GPU slot for $field'),
          ValueCouplingTarget(:final parent, :final child) =>
            'a${parent}_$child',
          VolatilityCouplingTarget(:final parent, :final child) =>
            'k${parent}_$child',
          ResponseTarget(:final name) => 'rp${responseNames.indexOf(name)}',
        };
        paramOf[v] = i;
      }
    }
    final nIn = model.network.inputIdxs.length;
    final trial = c.compile(
      _FitSource(nIn),
      seeds: kt > 0 ? paramOf.keys.toSet() : const {},
    );
    final slotOfVar = trial.slotOfVar;
    final nSlots = c.nSlots + k;
    final total = c.totalSlot;
    final src = StringBuffer()
      ..writeln(
        '// Generated by package:hgf_gpu: the likelihood of a '
        '${c.n}-node model${kt > 0 ? ' with $k tangent directions' : ''}'
        '${reverse ? ' (reverse mode: the primal, with checkpoints)' : ''}.',
      )
      ..writeln('struct Params { B: u32, t0: u32, nT: u32, dt: f32 }')
      ..writeln(
        '@group(0) @binding(0) var<storage, read_write> state: array<f32>;',
      )
      ..writeln('@group(0) @binding(1) var<storage, read> data: array<u32>;')
      ..writeln('@group(0) @binding(2) var<uniform> params: Params;')
      ..writeln('@group(0) @binding(3) var<storage, read> job: array<u32>;')
      ..writeln('@group(0) @binding(4) var<storage, read> subj: array<u32>;');
    if (kt > 0) {
      src.writeln(
        '@group(0) @binding(5) var<storage, read_write> tang: array<f32>;',
      );
    }
    if (reverse) {
      src.writeln(
        '@group(0) @binding(5) var<storage, read_write> tape: array<f32>;',
      );
    }
    src
      ..writeln(prelude)
      ..writeln(_fitPrelude)
      ..writeln('@compute @workgroup_size($workgroupSize)')
      ..writeln('fn main(@builtin(global_invocation_id) gid: vec3<u32>) {')
      ..writeln('  let B = params.B;')
      ..writeln('  let e = gid.x;')
      ..writeln('  if (e >= B) { return; }')
      ..writeln('  let sj = job[e] * ${subjectStride}u;')
      ..writeln('  let nTime = subj[sj];')
      ..writeln('  let inOff = subj[sj + 1u];')
      ..writeln('  let obsOff = subj[sj + 2u];')
      ..writeln('  let stepOff = subj[sj + 3u];')
      ..writeln('  let respOff = subj[sj + 4u];')
      ..writeln('  let xo = B + ${c.nSlots}u;');
    final loads = slotOfVar.keys.where(trial.carried.contains).toList();
    final activeLoads = loads.where(trial.active.contains).toList();
    for (final v in loads) {
      src.writeln('  var $v: f32;');
    }
    void tangentDecl(String v, String init) {
      for (var ch = 0; ch < c.chunks; ch++) {
        src.writeln(
          '  var ${v}_t$ch${init.isEmpty ? ': ${c.chunkType(ch)}' : ' = ${c.chunkType(ch)}()'};',
        );
      }
    }

    for (final v in activeLoads) {
      tangentDecl(v, '');
    }
    src
      ..writeln('  var total: f32;')
      ..writeln('  var comp: f32;')
      ..writeln('  var bad: bool;');
    if (kt > 0) tangentDecl('total', '');
    // First dispatch: initial slots, parameters and their seeds.
    src.writeln('  if (params.t0 == 0u) {');
    for (final v in loads) {
      final i = paramOf[v];
      src.writeln(
        i != null
            ? '    $v = bitcast<f32>(job[xo + ${i}u * B + e]);'
            : '    $v = bitcast<f32>(job[B + ${slotOfVar[v]}u]);',
      );
    }
    String seedChunk(int? i, int ch) {
      final w = c.chunkWidth(ch);
      final parts = [
        for (var d = 4 * ch; d < 4 * ch + w; d++)
          d == i ? 'bitcast<f32>(job[xo + ${k + d}u * B + e])' : '0.0f',
      ];
      return w == 1 ? parts.single : '${c.chunkType(ch)}(${parts.join(', ')})';
    }

    for (final v in activeLoads) {
      for (var ch = 0; ch < c.chunks; ch++) {
        src.writeln('    ${v}_t$ch = ${seedChunk(paramOf[v], ch)};');
      }
    }
    src
      ..writeln('    total = 0.0f;')
      ..writeln('    comp = 0.0f;')
      ..writeln('    bad = false;');
    for (var ch = 0; ch < c.chunks; ch++) {
      src.writeln('    total_t$ch = ${c.chunkType(ch)}();');
    }
    // Later dispatches: where the last one stopped.
    String loadChunk(int slot, int ch) {
      final w = c.chunkWidth(ch);
      final parts = [
        for (var d = 4 * ch; d < 4 * ch + w; d++)
          'tang[(${slot}u * ${k}u + ${d}u) * B + e]',
      ];
      return w == 1 ? parts.single : '${c.chunkType(ch)}(${parts.join(', ')})';
    }

    src.writeln('  } else {');
    for (final v in loads) {
      src.writeln('    $v = state[${slotOfVar[v]}u * B + e];');
    }
    for (final v in activeLoads) {
      for (var ch = 0; ch < c.chunks; ch++) {
        src.writeln('    ${v}_t$ch = ${loadChunk(slotOfVar[v]!, ch)};');
      }
    }
    src
      ..writeln('    total = state[${total}u * B + e];')
      ..writeln('    comp = state[${total + 1}u * B + e];')
      ..writeln('    bad = state[${total + 2}u * B + e] != 0.0f;');
    for (var ch = 0; ch < c.chunks; ch++) {
      src.writeln('    total_t$ch = ${loadChunk(total, ch)};');
    }
    src.writeln('  }');
    // Written but not carried: declared, not loaded.
    for (final v in slotOfVar.keys) {
      if (trial.written.contains(v) && !trial.carried.contains(v)) {
        src.writeln('  var $v = 0.0f;');
        if (trial.active.contains(v)) tangentDecl(v, '0');
      }
    }
    src
      ..writeln('  let tEnd = min(params.t0 + params.nT, nTime);')
      ..writeln('  for (var t = params.t0; t < tEnd; t++) {');
    final nC = loads.length;
    if (reverse) {
      src.writeln('    if (t % ${checkpoint}u == 0u) {');
      for (var j = 0; j < nC; j++) {
        src.writeln(
          '      tape[((t / ${checkpoint}u) * ${nC}u + ${j}u) * B + e] = '
          '${loads[j]};',
        );
      }
      src.writeln('    }');
    }
    src
      ..writeln('    let dt = stepAt(stepOff, t);')
      ..writeln('    let logT = select(log(dt), 0.0f, dt == 1.0f);')
      ..write(trial.body)
      ..writeln('  }');
    String component(int d) {
      final ch = d ~/ 4;
      return c.chunkWidth(ch) == 1 ? '' : '[${d % 4}]';
    }

    for (final v in loads) {
      src.writeln('  state[${slotOfVar[v]}u * B + e] = $v;');
    }
    for (final v in activeLoads) {
      final s = slotOfVar[v]!;
      for (var d = 0; d < k; d++) {
        src.writeln(
          '  tang[(${s}u * ${k}u + ${d}u) * B + e] = '
          '${v}_t${d ~/ 4}${component(d)};',
        );
      }
    }
    src
      ..writeln('  state[${total}u * B + e] = total;')
      ..writeln('  state[${total + 1}u * B + e] = comp;')
      ..writeln('  state[${total + 2}u * B + e] = select(0.0f, 1.0f, bad);')
      ..writeln(
        '  state[${total + 3}u * B + e] = select(total, 3.4e38f, bad);',
      );
    for (var d = 0; d < kt; d++) {
      src
        ..writeln(
          '  tang[(${total}u * ${k}u + ${d}u) * B + e] = '
          'total_t${d ~/ 4}${component(d)};',
        )
        ..writeln(
          '  state[${total + 4 + d}u * B + e] = '
          'total_t${d ~/ 4}${component(d)};',
        );
    }
    src.writeln('}');

    return FitKernel._(
      source: src.toString(),
      reverseSource: reverse
          ? _reverseSource(
              c,
              trial,
              loads,
              paramOf,
              k,
              checkpoint,
              nIn,
              workgroupSize,
            )
          : null,
      checkpoint: reverse ? checkpoint : 0,
      tapeCarried: loads.length,
      nSlots: nSlots,
      resultSlot: c.resultSlot,
      directions: k,
      initial: c.initialSlots(),
      workgroupSize: workgroupSize,
      nInputs: nIn,
      usesResponses: response.usesResponses,
    );
  }

  /// The reverse sweep (see the class comment).
  static String _reverseSource(
    TrialCompiler c,
    CompiledTrial trial,
    List<String> loads,
    Map<String, int> paramOf,
    int k,
    int cp,
    int nIn,
    int workgroupSize,
  ) {
    final ssa = c.compileSsa(_FitSource(nIn));
    final slotOfVar = trial.slotOfVar;
    final nC = loads.length;
    final total = c.totalSlot;
    final carried = [
      for (final v in loads)
        if (ssa.carried.contains(v)) v,
    ];
    final names = {for (final (n, _) in ssa.statements) n};
    final adj = Adjoints((n) => names.contains(n) || ssa.carried.contains(n));
    for (final (n, e) in ssa.statements.reversed) {
      adj.statement(n, e);
    }
    final src = StringBuffer()
      ..writeln(
        '// Generated by package:hgf_gpu: the reverse sweep of a '
        '${c.n}-node model, $k parameters, a checkpoint every $cp trials.',
      )
      ..writeln('struct Params { B: u32, sgHi: u32, count: u32, nSeg: u32 }')
      ..writeln(
        '@group(0) @binding(0) var<storage, read_write> state: array<f32>;',
      )
      ..writeln('@group(0) @binding(1) var<storage, read> data: array<u32>;')
      ..writeln('@group(0) @binding(2) var<uniform> params: Params;')
      ..writeln('@group(0) @binding(3) var<storage, read> job: array<u32>;')
      ..writeln('@group(0) @binding(4) var<storage, read> subj: array<u32>;')
      ..writeln(
        '@group(0) @binding(5) var<storage, read_write> tape: array<f32>;',
      )
      ..writeln(
        '@group(0) @binding(6) var<storage, read_write> seg: array<f32>;',
      )
      ..writeln(
        '@group(0) @binding(7) var<storage, read_write> adj: array<f32>;',
      )
      ..writeln(prelude)
      ..writeln(_fitPrelude)
      ..writeln('@compute @workgroup_size($workgroupSize)')
      ..writeln('fn main(@builtin(global_invocation_id) gid: vec3<u32>) {')
      ..writeln('  let B = params.B;')
      ..writeln('  let e = gid.x;')
      ..writeln('  if (e >= B) { return; }')
      ..writeln('  let sj = job[e] * ${subjectStride}u;')
      ..writeln('  let nTime = subj[sj];')
      ..writeln('  let inOff = subj[sj + 1u];')
      ..writeln('  let obsOff = subj[sj + 2u];')
      ..writeln('  let stepOff = subj[sj + 3u];')
      ..writeln('  let respOff = subj[sj + 4u];')
      ..writeln('  let xo = B + ${c.nSlots}u;');
    // The primal's variables, for recomputing a segment.
    for (final v in loads) {
      src.writeln('  var $v: f32;');
    }
    for (final v in slotOfVar.keys) {
      if (trial.written.contains(v) && !trial.carried.contains(v)) {
        src.writeln('  var $v = 0.0f;');
      }
    }
    src
      ..writeln('  var total = 0.0f;')
      ..writeln('  var comp = 0.0f;')
      ..writeln('  var bad = false;');
    // The carried adjoints: zero at the end of the series, else where the
    // last dispatch stopped.
    final first = 'params.sgHi == params.nSeg';
    for (var j = 0; j < carried.length; j++) {
      final v = carried[j];
      src.writeln('  var ${v}_b = select(adj[${j}u * B + e], 0.0f, $first);');
    }
    String tapeAt(String entry, int j) =>
        'tape[(($entry) * ${nC}u + ${j}u) * B + e]';
    String segAt(String entry, int j) =>
        'seg[(($entry) * ${nC}u + ${j}u) * B + e]';
    src
      ..writeln('  let sgLo = params.sgHi - min(params.count, params.sgHi);')
      ..writeln('  for (var sg = params.sgHi; sg > sgLo; ) {')
      ..writeln('    sg--;')
      ..writeln('    let t0 = sg * ${cp}u;')
      ..writeln('    let t1 = min(t0 + ${cp}u, nTime);')
      ..writeln('    if (t0 >= t1) { continue; }');
    for (var j = 0; j < nC; j++) {
      src.writeln('    ${loads[j]} = ${tapeAt('sg', j)};');
    }
    src.writeln('    for (var t = t0; t < t1; t++) {');
    for (var j = 0; j < nC; j++) {
      src.writeln('      ${segAt('t - t0', j)} = ${loads[j]};');
    }
    src
      ..writeln('      let dt = stepAt(stepOff, t);')
      ..writeln('      let logT = select(log(dt), 0.0f, dt == 1.0f);')
      ..write(trial.body.replaceAll(RegExp(r'^', multiLine: true), '  '))
      ..writeln('    }')
      ..writeln('    for (var t = t1; t > t0; ) {')
      ..writeln('      t--;')
      ..writeln('      let dt = stepAt(stepOff, t);')
      ..writeln('      let logT = select(log(dt), 0.0f, dt == 1.0f);');
    // The SSA body reads the carried slots under their own names: these
    // `let`s shadow the primal's `var`s.
    for (final v in carried) {
      src.writeln('      let $v = ${segAt('t - t0', loads.indexOf(v))};');
    }
    for (final l in ssa.body.split('\n')) {
      if (l.trim().isNotEmpty) src.writeln('      ${l.trim()}');
    }
    for (final n in names) {
      src.writeln('      var ${n}_b = 0.0f;');
    }
    src.writeln('      ${ssa.objective}_b = 1.0f;');
    // The adjoint flowing in from the next trial goes to each written
    // slot's last version; the start-of-trial adjoint restarts at 0.
    for (final v in carried) {
      final f = ssa.finalVersion[v];
      if (f == null) continue;
      src
        ..writeln('      ${f}_b += ${v}_b;')
        ..writeln('      ${v}_b = 0.0f;');
    }
    for (final l in adj.lines) {
      src.writeln('      $l');
    }
    src
      ..writeln('    }')
      ..writeln('  }')
      ..writeln('  if (sgLo > 0u) {');
    for (var j = 0; j < carried.length; j++) {
      src.writeln('    adj[${j}u * B + e] = ${carried[j]}_b;');
    }
    src
      ..writeln('    return;')
      ..writeln('  }');
    // ∂L/∂y_i = Σ over the slots parameter i sets of their adjoint, × dx/dy.
    for (var i = 0; i < k; i++) {
      final terms = [
        for (final MapEntry(key: v, value: p) in paramOf.entries)
          if (p == i && carried.contains(v)) '${v}_b',
      ];
      src.writeln(
        '  state[${total + 4 + i}u * B + e] = '
        '${terms.isEmpty ? '0.0f' : '(${terms.join(' + ')})'} * '
        'bitcast<f32>(job[xo + ${k + i}u * B + e]);',
      );
    }
    src.writeln('}');
    return src.toString();
  }

  FitKernel._({
    required this.source,
    required this.reverseSource,
    required this.checkpoint,
    required this.tapeCarried,
    required this.nSlots,
    required this.resultSlot,
    required this.directions,
    required this.initial,
    required this.workgroupSize,
    required this.nInputs,
    required this.usesResponses,
  });

  /// The likelihood (and in forward mode the gradient) kernel.
  final String source;

  /// Reverse mode: the backward sweep; `null` in forward mode.
  final String? reverseSource;

  /// Reverse mode: trials per checkpoint (0 in forward mode).
  final int checkpoint;

  /// Carried slots per checkpoint.
  final int tapeCarried;

  /// Whether the gradient comes from reverse mode.
  bool get reverse => reverseSource != null;

  /// Reverse mode: checkpoints for series of up to [maxTime] trials.
  int segments(int maxTime) =>
      reverse ? math.max(1, (maxTime + checkpoint - 1) ~/ checkpoint) : 0;

  /// Slots per element in the state buffer (the result and gradient last).
  final int nSlots;

  /// Slot of the negative log-likelihood; the gradient follows.
  final int resultSlot;

  /// Tangent directions (the model's dimension with gradients, else 0).
  final int directions;

  /// The network's initial value of every slot (before the gradient
  /// slots), uploaded with each pass.
  final List<double> initial;

  final int workgroupSize;
  final int nInputs;
  final bool usesResponses;

  /// Slots of the tangent buffer per element and direction.
  int get tangentSlots => resultSlot + 1;
}

/// The kernel response for [response], or throws [UnsupportedError]
/// ([irResponseOf]).
GpuResponse gpuResponseOf(ResponseModel response) => irResponseOf(response);

final class _FitSource implements TrialSource {
  _FitSource(this.nIn);

  final int nIn;

  @override
  String input(int c) => 'bitcast<f32>(data[inOff + t * ${nIn}u + ${c}u])';

  @override
  String observed(int c) => 'maskAt(obsOff, t * ${nIn}u + ${c}u)';

  @override
  String responsePresent() => 'respPresent(respOff, t)';

  @override
  String response() => 'respAt(respOff, t)';
}

const String _fitPrelude =
    '''
fn maskAt(off: u32, i: u32) -> f32 {
  if (off == ${noData}u) { return 1.0f; }
  return bitcast<f32>(data[off + i]);
}
fn stepAt(off: u32, t: u32) -> f32 {
  if (off == ${noData}u) { return 1.0f; }
  return bitcast<f32>(data[off + t]);
}
fn respPresent(off: u32, t: u32) -> bool {
  if (off == ${noData}u) { return false; }
  return (data[off + t] & 0x7fffffffu) <= 0x7f800000u;
}
fn respAt(off: u32, t: u32) -> f32 {
  if (off == ${noData}u) { return 0.0f; }
  return bitcast<f32>(data[off + t]);
}
''';

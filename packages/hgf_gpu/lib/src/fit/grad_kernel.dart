// Reverse-mode spike (2026-11-11): gradient kernels for one shared input
// series, in forward mode (tangents) and reverse mode (adjoints), behind one
// harness so their costs compare like for like. Not exported.
import 'dart:typed_data';

import 'package:hgf/hgf.dart' hide lambertW0, logAddExp;

import '../batch.dart';
import '../ir.dart';
import '../trial.dart';

/// How a [GradKernel] differentiates.
enum GradMode {
  /// No derivatives: the likelihood alone.
  primal,

  /// Forward-mode tangents along `directions` directions.
  forward,

  /// Reverse mode, every trial's carried state on a tape.
  reverseTape,

  /// Reverse mode, the state at every `checkpoint`-th trial; each segment
  /// is recomputed into a segment tape on the way back.
  reverseCheckpoint,
}

/// The likelihood of [network] under [response] over one shared series of
/// `nT` trials (`data[t][input]`, every input observed, `dt` = 1), for a
/// batch of elements with per-element initial slots, and its gradient.
///
/// Bindings (group 0): 0 `state` (read `f32`, `[slot][element]`, the
/// initial slots), 1 `data` (`f32`), 2 `params` (uniform: `B`, `nT`), 3
/// `resp` (`f32`, `[t][element]`; bound but unused without responses), 4
/// `tape` (read_write `f32`; reverse modes), 5 `out` (read_write `f32`:
/// `[0][e]` the negative log-likelihood, then `[1 + i][e]` the derivative
/// along direction or parameter `i`).
///
/// Forward mode seeds direction `d` with parameter `d % params.length`
/// (more directions than parameters cost what distinct ones would; only
/// the first `params.length` are distinct). Reverse mode returns the
/// derivative with respect to the initial value of every slot in
/// [params] (zero for a slot the likelihood never reads).
final class GradKernel {
  factory GradKernel(
    Network network,
    GpuResponse response, {
    required List<String> params,
    GradMode mode = GradMode.forward,
    int directions = 0,
    int checkpoint = 0,
    int workgroupSize = 64,
  }) {
    final reverse =
        mode == GradMode.reverseTape || mode == GradMode.reverseCheckpoint;
    final k = mode == GradMode.forward ? directions : 0;
    if (mode == GradMode.forward && k <= 0) {
      throw ArgumentError.value(directions, 'directions', 'Must be > 0');
    }
    if (mode == GradMode.reverseCheckpoint && checkpoint < 2) {
      throw ArgumentError.value(checkpoint, 'checkpoint', 'Must be ≥ 2');
    }
    final c = TrialCompiler(network, response, directions: k);
    final nIn = network.inputIdxs.length;
    final source = _Source(nIn);
    final trial = c.compile(source, seeds: k > 0 ? params.toSet() : const {});
    final slotOfVar = trial.slotOfVar;
    final loads = slotOfVar.keys.where(trial.carried.contains).toList();
    final outputs = switch (mode) {
      GradMode.primal => 0,
      GradMode.forward => k,
      _ => params.length,
    };
    final src = StringBuffer()
      ..writeln(
        '// Generated by package:hgf_gpu (reverse-mode spike): '
        '${mode.name}${k > 0 ? ', $k directions' : ''}.',
      )
      ..writeln('struct Params { B: u32, nT: u32 }')
      ..writeln('@group(0) @binding(0) var<storage, read> state: array<f32>;')
      ..writeln('@group(0) @binding(1) var<storage, read> data: array<f32>;')
      ..writeln('@group(0) @binding(2) var<uniform> params: Params;');
    if (response.usesResponses) {
      src.writeln('@group(0) @binding(3) var<storage, read> resp: array<f32>;');
    }
    if (reverse) {
      src.writeln(
        '@group(0) @binding(4) var<storage, read_write> tape: array<f32>;',
      );
    }
    src
      ..writeln(
        '@group(0) @binding(5) var<storage, read_write> out: array<f32>;',
      )
      ..writeln(prelude)
      ..writeln('@compute @workgroup_size($workgroupSize)')
      ..writeln('fn main(@builtin(global_invocation_id) gid: vec3<u32>) {')
      ..writeln('  let B = params.B;')
      ..writeln('  let e = gid.x;')
      ..writeln('  if (e >= B) { return; }')
      ..writeln('  let nT = params.nT;')
      ..writeln('  let dt = 1.0f;')
      ..writeln('  let logT = 0.0f;');
    for (final v in loads) {
      src.writeln('  var $v = state[${slotOfVar[v]}u * B + e];');
    }
    for (final v in slotOfVar.keys) {
      if (trial.written.contains(v) && !trial.carried.contains(v)) {
        src.writeln('  var $v = 0.0f;');
        if (trial.active.contains(v)) {
          for (var ch = 0; ch < c.chunks; ch++) {
            src.writeln('  var ${v}_t$ch = ${c.chunkType(ch)}();');
          }
        }
      }
    }
    if (k > 0) {
      // Seeds: direction d along parameter d % params.length.
      for (final v in loads.where(trial.active.contains)) {
        final p = params.indexOf(v);
        for (var ch = 0; ch < c.chunks; ch++) {
          final w = c.chunkWidth(ch);
          final parts = [
            for (var d = 4 * ch; d < 4 * ch + w; d++)
              p >= 0 && d % params.length == p ? '1.0f' : '0.0f',
          ];
          src.writeln(
            '  var ${v}_t$ch = '
            '${w == 1 ? parts.single : '${c.chunkType(ch)}(${parts.join(', ')})'};',
          );
        }
      }
      for (var ch = 0; ch < c.chunks; ch++) {
        src.writeln('  var total_t$ch = ${c.chunkType(ch)}();');
      }
    }
    src
      ..writeln('  var total = 0.0f;')
      ..writeln('  var comp = 0.0f;')
      ..writeln('  var bad = false;');

    // Tape layout: [entry][carried slot][element].
    final nC = loads.length;
    String tapeAt(String entry, int j) =>
        'tape[(($entry) * ${nC}u + ${j}u) * B + e]';
    void store(String entry, String indent) {
      for (var j = 0; j < nC; j++) {
        src.writeln('$indent${tapeAt(entry, j)} = ${loads[j]};');
      }
    }

    // Forward sweep.
    src.writeln('  for (var t = 0u; t < nT; t++) {');
    if (mode == GradMode.reverseTape) store('t', '    ');
    if (mode == GradMode.reverseCheckpoint) {
      src.writeln('    if (t % ${checkpoint}u == 0u) {');
      store('t / ${checkpoint}u', '      ');
      src.writeln('    }');
    }
    src
      ..write(trial.body)
      ..writeln('  }')
      ..writeln('  out[e] = select(total, 3.4e38f, bad);');

    if (mode == GradMode.forward) {
      for (var d = 0; d < k; d++) {
        final comp = c.chunkWidth(d ~/ 4) == 1 ? '' : '[${d % 4}]';
        src.writeln('  out[${1 + d}u * B + e] = total_t${d ~/ 4}$comp;');
      }
    }

    if (reverse) {
      final ssa = c.compileSsa(source);
      final carried = ssa.carried.toList();
      // Every carried slot's adjoint (w.r.t. its value at trial start).
      for (final v in carried) {
        src.writeln('  var ${v}_b = 0.0f;');
      }
      final names = {for (final (n, _) in ssa.statements) n};
      final adj = Adjoints((n) => names.contains(n) || ssa.carried.contains(n));
      for (final (n, e) in ssa.statements.reversed) {
        adj.statement(n, e);
      }
      void step(String indent, void Function() load) {
        load();
        for (final l in ssa.body.split('\n')) {
          if (l.trim().isNotEmpty) src.writeln('$indent${l.trim()}');
        }
        for (final n in names) {
          src.writeln('${indent}var ${n}_b = 0.0f;');
        }
        src.writeln('$indent${ssa.objective}_b = 1.0f;');
        // The adjoint flowing in from the next trial goes to each written
        // slot's last version; the start-of-trial adjoint restarts at 0.
        for (final v in carried) {
          final f = ssa.finalVersion[v];
          if (f == null) continue;
          src
            ..writeln('$indent${f}_b += ${v}_b;')
            ..writeln('$indent${v}_b = 0.0f;');
        }
        for (final l in adj.lines) {
          src.writeln('$indent$l');
        }
      }

      // The SSA body reads the carried slots under their own names: a
      // `let` per carried slot shadows the sweep's `var`s.
      int j(String v) => loads.indexOf(v);
      if (mode == GradMode.reverseTape) {
        src.writeln('  for (var t = nT; t > 0u; ) {');
        src.writeln('    t--;');
        step('    ', () {
          for (final v in carried) {
            src.writeln('    let $v = ${tapeAt('t', j(v))};');
          }
        });
        src.writeln('  }');
      } else {
        // Checkpoints at [0, nCk), then the segment tape.
        final cp = checkpoint;
        src
          ..writeln('  let nCk = (nT + ${cp - 1}u) / ${cp}u;')
          ..writeln('  for (var sg = nCk; sg > 0u; ) {')
          ..writeln('    sg--;')
          ..writeln('    let t0 = sg * ${cp}u;')
          ..writeln('    let t1 = min(t0 + ${cp}u, nT);');
        for (var q = 0; q < nC; q++) {
          src.writeln('    ${loads[q]} = ${tapeAt('sg', q)};');
        }
        src.writeln('    for (var t = t0; t < t1; t++) {');
        store('nCk + t - t0', '      ');
        src
          ..write(trial.body.replaceAll(RegExp(r'^', multiLine: true), '  '))
          ..writeln('    }')
          ..writeln('    for (var t = t1; t > t0; ) {')
          ..writeln('      t--;');
        step('      ', () {
          for (final v in carried) {
            src.writeln('      let $v = ${tapeAt('nCk + t - t0', j(v))};');
          }
        });
        src
          ..writeln('    }')
          ..writeln('  }');
      }
      for (var i = 0; i < params.length; i++) {
        final v = params[i];
        src.writeln(
          '  out[${1 + i}u * B + e] = '
          '${ssa.carried.contains(v) ? '${v}_b' : '0.0f'};',
        );
      }
    }
    src.writeln('}');

    return GradKernel._(
      source: src.toString(),
      mode: mode,
      outputs: outputs,
      nSlots: c.nSlots,
      tapeCarried: nC,
      checkpoint: checkpoint,
      initial: c.initialSlots(),
      slotOfVar: slotOfVar,
      workgroupSize: workgroupSize,
    );
  }

  GradKernel._({
    required this.source,
    required this.mode,
    required this.outputs,
    required this.nSlots,
    required this.tapeCarried,
    required this.checkpoint,
    required this.initial,
    required this.slotOfVar,
    required this.workgroupSize,
  });

  final String source;
  final GradMode mode;

  /// Derivatives per element in `out` (after the likelihood).
  final int outputs;

  /// Slots per element in `state`.
  final int nSlots;

  /// Carried slots per tape entry.
  final int tapeCarried;
  final int checkpoint;

  /// The network's initial slots.
  final List<double> initial;
  final Map<String, int> slotOfVar;
  final int workgroupSize;

  /// Tape entries for a series of [nT] trials (0 without a tape).
  int tapeEntries(int nT) => switch (mode) {
    GradMode.reverseTape => nT,
    GradMode.reverseCheckpoint =>
      (nT + checkpoint - 1) ~/ checkpoint + checkpoint,
    _ => 0,
  };

  /// Tape bytes for [batch] elements over [nT] trials.
  int tapeBytes(int batch, int nT) => tapeEntries(nT) * tapeCarried * batch * 4;
}

/// A [GradKernel] bound to its buffers on [backend], for repeated runs.
final class GradJob {
  /// [slots]: every element's initial slots, `[slot][element]` ([GradKernel.nSlots]
  /// × [batch]); [data]: `[t][input]`; [responses]: `[t][element]` or null.
  static Future<GradJob> create(
    GpuBackend backend,
    GradKernel kernel, {
    required int batch,
    required int nT,
    required Float32List slots,
    required Float32List data,
    Float32List? responses,
  }) async {
    final pipeline = await backend.pipeline(kernel.source);
    GpuBuffer upload(Float32List x) {
      final b = backend.storage(x.lengthInBytes < 16 ? 16 : x.lengthInBytes);
      backend.write(b, x);
      return b;
    }

    final params = backend.uniform(16);
    backend.writeUints(params, Uint32List.fromList([batch, nT, 0, 0]));
    final tapeBytes = kernel.tapeBytes(batch, nT);
    return GradJob._(backend, kernel, pipeline, batch, [
      upload(slots),
      upload(data),
      params,
      responses == null ? null : upload(responses),
      tapeBytes > 0 ? backend.storage(tapeBytes) : null,
      backend.storage((1 + kernel.outputs) * batch * 4),
    ]);
  }

  GradJob._(
    this.backend,
    this.kernel,
    this.pipeline,
    this.batch,
    this.bindings,
  );

  final GpuBackend backend;
  final GradKernel kernel;
  final GpuPipeline pipeline;
  final int batch;
  final List<GpuBuffer?> bindings;

  /// Queues one dispatch.
  void dispatch() => backend.dispatch(
    pipeline,
    bindings,
    (batch + kernel.workgroupSize - 1) ~/ kernel.workgroupSize,
  );

  /// Runs once and reads `out`: `[0][e]` the likelihood, `[1 + i][e]` the
  /// derivatives.
  Future<Float32List> run() async {
    dispatch();
    return backend.read(bindings[5]!, bytes: (1 + kernel.outputs) * batch * 4);
  }

  void release() {
    for (final b in bindings) {
      if (b != null) backend.release(b);
    }
  }
}

final class _Source implements TrialSource {
  _Source(this.nIn);

  final int nIn;

  @override
  String input(int c) => 'data[t * ${nIn}u + ${c}u]';

  @override
  String observed(int c) => '1.0f';

  @override
  String responsePresent() => 'true';

  @override
  String response() => 'resp[t * B + e]';
}

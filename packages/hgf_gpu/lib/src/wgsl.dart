import 'dart:typed_data';

import 'package:hgf/hgf.dart';

import 'trial.dart';

export 'trial.dart'
    show GpuBinarySoftmax, GpuGaussianReadout, GpuResponse, gpuNodeFields;

/// A [Network] compiled into a WGSL compute shader: one invocation per
/// batch element (parameter set), looping over a range of trials with the
/// element's whole state in registers.
///
/// Everything per element lives in one `f32` storage buffer, `[slot][element]`
/// (element innermost, so a workgroup's loads coalesce): every node field of
/// [gpuNodeFields], every value and volatility coupling strength, the
/// response's parameters, and the running response total. A dispatch loads
/// the slots it reads, runs its trials and stores the slots it carries, so
/// any field, coupling or response parameter can differ per element without
/// recompiling, and a long series can be split over several dispatches.
///
/// The arithmetic is the [BatchNetwork]'s in `f32`, with the `f64`
/// constants moved into `f32` range. WGSL does not guarantee NaN or
/// infinity semantics, so the kernel does not rely on them: an element whose
/// state stops being finite is flagged and reports an infinite total, like
/// the CPU engine's `_nanToInf`.
final class HgfKernel {
  /// Compiles [network] (built if needed).
  ///
  /// [perElementData]: each element gets its own observations
  /// (`data[t][input][element]`) and responses (`responses[t][element]`)
  /// instead of sharing one series (`data[t][input]`, `responses[t]`).
  /// [observedMask]: the kernel reads a 0/1 mask with the same layout as
  /// the data (missing observations). A response model that scores
  /// responses ([GpuResponse.usesResponses]) reads one per trial; NaN marks
  /// a missed one.
  ///
  /// Throws [UnsupportedError] for node kinds and update steps without a
  /// GPU kernel (vector-valued nodes, custom couplings).
  factory HgfKernel(
    Network network, {
    GpuResponse response = GpuResponse.totalGaussianSurprise,
    bool perElementData = false,
    bool observedMask = false,
    bool timeSteps = false,
    int workgroupSize = 64,
  }) {
    final c = TrialCompiler(network, response);
    final nIn = network.inputIdxs.length;
    final trial = c.compile(_Source(nIn, perElementData, observedMask));
    var binding = 3;
    final src = StringBuffer()
      ..writeln('// Generated by package:hgf_gpu from a ${c.n}-node network.')
      ..writeln('struct Params { B: u32, t0: u32, nT: u32, dt: f32 }')
      ..writeln(
        '@group(0) @binding(0) var<storage, read_write> state: array<f32>;',
      )
      ..writeln('@group(0) @binding(1) var<storage, read> data: array<f32>;')
      ..writeln('@group(0) @binding(2) var<uniform> params: Params;');
    if (observedMask) {
      src.writeln(
        '@group(0) @binding(${binding++}) var<storage, read> mask: array<f32>;',
      );
    }
    if (timeSteps) {
      src.writeln(
        '@group(0) @binding(${binding++}) var<storage, read> steps: '
        'array<f32>;',
      );
    }
    if (response.usesResponses) {
      src.writeln(
        '@group(0) @binding($binding) var<storage, read> resp: array<u32>;',
      );
    }
    final total = c.totalSlot;
    src
      ..writeln(prelude)
      ..writeln('@compute @workgroup_size($workgroupSize)')
      ..writeln('fn main(@builtin(global_invocation_id) gid: vec3<u32>) {')
      ..writeln('  let B = params.B;')
      ..writeln('  let e = gid.x;')
      ..writeln('  if (e >= B) { return; }');
    if (!timeSteps) {
      src
        ..writeln('  let dt = params.dt;')
        ..writeln('  let logT = select(log(dt), 0.0f, dt == 1.0f);');
    }
    final slotOfVar = trial.slotOfVar;
    final loads = slotOfVar.keys.where(trial.carried.contains).toList();
    for (final v in loads) {
      final kw = trial.written.contains(v) ? 'var' : 'let';
      src.writeln('  $kw $v = state[${slotOfVar[v]}u * B + e];');
    }
    // Written but not carried: declared, not loaded.
    for (final v in slotOfVar.keys) {
      if (trial.written.contains(v) && !trial.carried.contains(v)) {
        src.writeln('  var $v = 0.0f;');
      }
    }
    src
      ..writeln('  var total = state[${total}u * B + e];')
      ..writeln('  var comp = state[${total + 1}u * B + e];')
      ..writeln('  var bad = state[${total + 2}u * B + e] != 0.0f;')
      ..writeln('  for (var t = params.t0; t < params.t0 + params.nT; t++) {');
    if (timeSteps) {
      src
        ..writeln('    let dt = steps[t];')
        ..writeln('    let logT = select(log(dt), 0.0f, dt == 1.0f);');
    }
    src
      ..write(trial.body)
      ..writeln('  }');
    // Stored: the slots carried between trials, plus the beliefs a caller
    // reads back.
    final stored = <String>{
      for (final v in trial.written)
        if (trial.carried.contains(v)) v,
      for (var i = 0; i < c.n; i++)
        for (final f in const [
          NodeField.mean,
          NodeField.precision,
          NodeField.expectedMean,
          NodeField.expectedPrecision,
        ])
          if (trial.written.contains(TrialCompiler.fieldVar(i, f)))
            TrialCompiler.fieldVar(i, f),
    };
    for (final v in slotOfVar.keys.where(stored.contains)) {
      src.writeln('  state[${slotOfVar[v]}u * B + e] = $v;');
    }
    src
      ..writeln('  state[${total}u * B + e] = total;')
      ..writeln('  state[${total + 1}u * B + e] = comp;')
      ..writeln('  state[${total + 2}u * B + e] = select(0.0f, 1.0f, bad);')
      ..writeln('  state[${total + 3}u * B + e] = select(total, 3.4e38f, bad);')
      ..writeln('}');

    return HgfKernel._(
      compiler: c,
      source: src.toString(),
      initial: Float64List.fromList(c.initialSlots()),
      inputs: List.unmodifiable(network.inputIdxs),
      response: response,
      perElementData: perElementData,
      observedMask: observedMask,
      timeSteps: timeSteps,
      workgroupSize: workgroupSize,
      loaded: loads.length,
      stored: stored.length,
    );
  }

  HgfKernel._({
    required TrialCompiler compiler,
    required this.source,
    required this.initial,
    required this.inputs,
    required this.response,
    required this.perElementData,
    required this.observedMask,
    required this.timeSteps,
    required this.workgroupSize,
    required this.loaded,
    required this.stored,
  }) : _c = compiler;

  final TrialCompiler _c;

  /// The WGSL source. Entry point `main`; bindings in group 0:
  /// 0 `state` (read_write), 1 `data` (read), 2 `params` (uniform:
  /// batch size, first trial, trial count, time step), then `mask` (read,
  /// only with [observedMask]), `steps` (read, only with [timeSteps]) and
  /// `resp` (read, only if the response scores responses).
  final String source;

  int get nNodes => _c.n;

  /// Slots per element in the state buffer.
  int get nSlots => _c.nSlots;

  /// `(parent, child)` per value edge, in slot order after the node fields.
  List<(int, int)> get valueEdges => List.unmodifiable(_c.valueEdges);

  /// `(parent, child)` per volatility edge, after the value edges.
  List<(int, int)> get volatilityEdges => List.unmodifiable(_c.volatilityEdges);

  /// The network's initial value of every slot, the response parameters'
  /// defaults (the total starts at 0).
  final Float64List initial;

  /// The input nodes, in data-column order.
  final List<int> inputs;

  final GpuResponse response;
  final bool perElementData;
  final bool observedMask;

  /// The kernel reads one time step per trial (`steps[t]`) instead of the
  /// dispatch's uniform one.
  final bool timeSteps;
  final int workgroupSize;

  /// How many slots a dispatch loads and stores (diagnostic).
  final int loaded, stored;

  /// Slot of [field] of [node].
  int slot(int node, NodeField field) => _c.slot(node, field);

  /// Slot of the value coupling `parent → child`.
  int valueCouplingSlot(int parent, int child) =>
      _c.valueCouplingSlot(parent, child);

  /// Slot of the volatility coupling `parent → child`.
  int volatilityCouplingSlot(int parent, int child) =>
      _c.volatilityCouplingSlot(parent, child);

  /// Slot of the response's parameter [j] (in [GpuResponse.defaults]
  /// order).
  int responseParameterSlot(int j) {
    RangeError.checkValidIndex(j, response.defaults, 'j');
    return _c.responseSlot(j);
  }

  /// Slot of the running response total (Kahan sum; the next slot holds
  /// its compensation, the one after that the non-finite flag).
  int get totalSlot => _c.totalSlot;

  /// Slot of the result: the total, or `f32` max where the flag is set
  /// (WGSL has no infinity literal; Tint rejects even a bitcast one).
  int get resultSlot => _c.resultSlot;

  /// A state buffer for [batchSize] elements, every element at the
  /// network's initial values.
  Float32List initialState(int batchSize) {
    final out = Float32List(nSlots * batchSize);
    for (var s = 0; s < nSlots; s++) {
      out.fillRange(s * batchSize, (s + 1) * batchSize, initial[s]);
    }
    return out;
  }

  /// Width of one trial's row of shared data.
  int get nInputs => inputs.length;
}

final class _Source implements TrialSource {
  _Source(this.nIn, this.perElement, this.mask);

  final int nIn;
  final bool perElement, mask;

  String _at(int c) =>
      perElement ? '(t * ${nIn}u + ${c}u) * B + e' : 't * ${nIn}u + ${c}u';

  String get _r => perElement ? 't * B + e' : 't';

  @override
  String input(int c) => 'data[${_at(c)}]';

  @override
  String observed(int c) => mask ? 'mask[${_at(c)}]' : '1.0f';

  @override
  String responsePresent() => '((resp[$_r] & 0x7fffffffu) <= 0x7f800000u)';

  @override
  String response() => 'bitcast<f32>(resp[$_r])';
}
